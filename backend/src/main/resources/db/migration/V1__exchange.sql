CREATE TABLE app_user (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(24) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE TABLE season (
 season_day DATE PRIMARY KEY,
 settled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE account (
 user_id BIGINT PRIMARY KEY,
 balance DECIMAL(30,10) NOT NULL,
 CONSTRAINT fk_account_user FOREIGN KEY(user_id) REFERENCES app_user(id)
);
CREATE TABLE asset (
 symbol VARCHAR(12) PRIMARY KEY,
 name VARCHAR(40) NOT NULL,
 universe VARCHAR(20) NOT NULL,
 sector VARCHAR(30) NOT NULL,
 initial_price DECIMAL(30,10) NOT NULL,
 base_reserve DECIMAL(30,10) NOT NULL,
 quote_reserve DECIMAL(30,10) NOT NULL,
 volume DECIMAL(30,10) NOT NULL DEFAULT 0
);
CREATE TABLE position_entry (
 id VARCHAR(36) PRIMARY KEY,
 user_id BIGINT NOT NULL,
 symbol VARCHAR(12) NOT NULL,
 side VARCHAR(5) NOT NULL,
 margin DECIMAL(30,10) NOT NULL,
 leverage INT NOT NULL,
 quantity DECIMAL(30,10) NOT NULL,
 entry_price DECIMAL(30,10) NOT NULL,
 opened_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES app_user(id),
 FOREIGN KEY(symbol) REFERENCES asset(symbol)
);
CREATE INDEX ix_position_symbol ON position_entry(symbol);
CREATE INDEX ix_position_user ON position_entry(user_id);
CREATE TABLE trade_record (
 id VARCHAR(36) PRIMARY KEY,
 user_id BIGINT NOT NULL,
 season_day DATE NOT NULL,
 symbol VARCHAR(12) NOT NULL,
 action VARCHAR(16) NOT NULL,
 side VARCHAR(5) NOT NULL,
 quantity DECIMAL(30,10) NOT NULL,
 price DECIMAL(30,10) NOT NULL,
 fee DECIMAL(30,10) NOT NULL,
 pnl DECIMAL(30,10) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE INDEX ix_trade_user ON trade_record(user_id, created_at);
CREATE TABLE command_receipt (
 user_id BIGINT NOT NULL,
 request_id VARCHAR(36) NOT NULL,
 fingerprint VARCHAR(200) NOT NULL,
 result_id VARCHAR(36) NOT NULL,
 PRIMARY KEY(user_id, request_id)
);
CREATE TABLE candle (
 symbol VARCHAR(12) NOT NULL,
 minute_at BIGINT NOT NULL,
 open_price DECIMAL(30,10) NOT NULL,
 high_price DECIMAL(30,10) NOT NULL,
 low_price DECIMAL(30,10) NOT NULL,
 close_price DECIMAL(30,10) NOT NULL,
 volume DECIMAL(30,10) NOT NULL,
 PRIMARY KEY(symbol,minute_at)
);
CREATE TABLE news (
 id VARCHAR(36) PRIMARY KEY,
 symbol VARCHAR(12) NOT NULL,
 title VARCHAR(160) NOT NULL,
 sentiment VARCHAR(12) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE INDEX ix_news_time ON news(created_at);
CREATE TABLE daily_ranking (
 season_day DATE NOT NULL,
 user_id BIGINT NOT NULL,
 username VARCHAR(24) NOT NULL,
 equity DECIMAL(30,10) NOT NULL,
 PRIMARY KEY(season_day,user_id)
);
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
 SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL,
 MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
 ATTRIBUTE_BYTES BLOB NOT NULL,
 PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
 CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
 REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
